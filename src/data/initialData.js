// Helper to get today's date in YYYY-MM-DD
export const getTodayDateStr = () => {
  const d = new Date();
  return d.toISOString().split('T')[0];
};

export const getOffsetDateStr = (offsetDays) => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().split('T')[0];
};

